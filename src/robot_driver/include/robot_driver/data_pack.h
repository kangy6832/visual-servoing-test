/**
 * @file data_pack.h
 * @brief 机器人数据包结构定义
 * 
 * 核心目的：
 * ---------------------
 * 定义机器人控制系统与硬件控制器之间通信的数据包结构。
 * 该文件提供了标准化的数据结构，用于在上位机（ROS2系统）和下位机（机器人控制器）
 * 之间传输关节状态和控制指令，确保数据格式的一致性和兼容性。
 * 
 * 具体功能：
 * -------------------
 * 1. 定义电机状态数据结构（Motor_t），包含角度、角速度和力矩信息
 * 2. 定义机械臂整体数据结构（Arm_t），包含数据包类型和6个关节状态
 * 3. 设置1字节对齐，确保与嵌入式系统的内存布局兼容
 * 4. 提供跨平台的数据交换格式
 * 
 * 数据结构说明：
 * -------------
 * - Motor_t: 单个电机的状态信息，用于关节级控制
 * - Arm_t: 整个机械臂的状态信息，用于系统级控制
 * 
 * 对齐设置：
 * ---------
 * 使用#pragma pack(1)强制1字节对齐，确保：
 * 1. 与嵌入式系统（如STM32）的内存布局一致
 * 2. 避免因平台差异导致的结构体填充问题
 * 3. 保证通过网络/USB传输的数据格式确定性
 * 
 * 使用场景：
 * ---------
 * - ROS2节点与机器人控制器的串行通信
 * - USB CDC数据传输
 * - 实时关节状态监控
 * - 运动控制指令传输
 * 
 * @author 系统开发者
 * @version 1.0
 * @date 2026年
 * @copyright 保留所有权利
 */

#ifndef __DATAPACK_H__
#define __DATAPACK_H__

// 设置结构体按1字节对齐，确保与嵌入式系统的内存布局兼容
// 这对于跨平台数据交换至关重要，避免因对齐方式不同导致的数据解析错误
#pragma pack(1)

/**
 * @brief 电机状态数据结构
 * 
 * @details 表示单个电机/关节的完整状态信息，包含位置、速度和力矩三环控制数据。
 *          该结构体用于在ROS2系统与机器人控制器之间传输关节级控制指令和状态反馈。
 * 
 * @var rad 关节角度，单位：弧度（rad）
 * @var omega 关节角速度，单位：弧度/秒（rad/s）
 * @var torque 关节输出力矩，单位：牛顿·米（N·m）
 * 
 * @note 所有字段使用float类型，确保与大多数嵌入式系统的兼容性
 * @warning 结构体大小为12字节（3个float），使用1字节对齐
 */
typedef struct {
    float rad;      /**< 电机的关节角度，单位：弧度（rad） */
    float omega;    /**< 电机的角速度，单位：弧度/秒（rad/s） */
    float torque;   /**< 电机输出力矩，单位：牛顿·米（N·m） */
} Motor_t;

/**
 * @brief 机械臂整体数据结构
 * 
 * @details 表示整个机械臂的状态信息，包含数据包类型和6个关节的完整状态。
 *          该结构体用于在ROS2系统与机器人控制器之间传输系统级控制指令和状态反馈。
 * 
 * @var pack_type 数据包类型标识，用于区分不同种类的数据包
 * @var joints 6个关节的电机状态数组，对应机械臂的6个自由度
 * 
 * @note 数据包类型为1表示关节状态/控制数据包
 * @warning 结构体大小为4 + 6*12 = 76字节，使用1字节对齐
 * @see Motor_t 单个关节的数据结构
 */
typedef struct {
    int pack_type;          /**< 数据包类型，用于标识数据包用途 */
    Motor_t joints[6];      /**< 机械臂的6个关节状态数组 */
} Arm_t;

// 将字节对齐设置恢复为默认值（通常是8字节）
// 避免影响文件中其他代码的对齐方式
#pragma pack()

#endif /* __DATAPACK_H__ */